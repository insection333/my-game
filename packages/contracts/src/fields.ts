// Fields shared by many routes. Names are what other players see on the hiscores, so they are
// short, plain and printable: letters, digits, single spaces, hyphens and underscores.
import { z } from 'zod';
import { CONTROL_CHARS, NAME_MAX, NAME_MIN, NAME_PATTERN, PASSWORD_MAX, PASSWORD_MIN } from './limits.ts';

export const PlayerName = z
  .string()
  .min(NAME_MIN)
  .max(NAME_MAX)
  .regex(NAME_PATTERN, 'letters, digits, single spaces, - and _; no space at either end');

export const plainText = (max: number, min = 1) =>
  z
    .string()
    .min(min)
    .max(max)
    .refine((s) => !CONTROL_CHARS.test(s), 'no control characters');

export const Password = plainText(PASSWORD_MAX, PASSWORD_MIN);

/** A request id: generated by the page for each action, so a retry or double click acts once. */
export const RequestId = z
  .string()
  .min(8)
  .max(64)
  .regex(/^[A-Za-z0-9_-]+$/);

export const Email = z.string().max(254).email();
export const Token = z
  .string()
  .min(20)
  .max(128)
  .regex(/^[A-Za-z0-9_-]+$/);

/** The key a name is unique by: "Rowan" and "rowan" are the same player. */
export const nameKey = (name: string) => name.toLowerCase();
